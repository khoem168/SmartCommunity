async function seedAllCourses() {
  console.log(`Starting to seed ${COURSES_DATA.length} courses...`);
  
  for (const c of COURSES_DATA) {
    // 1. Upsert course
    const [existing] = await db.query('SELECT id FROM courses WHERE slug = ?', [c.slug]);
    let courseId;
    if (existing && existing.length > 0) {
      courseId = existing[0].id;
      await db.query(
        `UPDATE courses
         SET title = ?, description = ?, category = ?, level = ?, instructor_name = ?,
             thumbnail_url = ?, highlights = ?, price = ?, currency = ?, duration_text = ?,
             sort_order = ?, is_published = 1, updated_at = NOW()
         WHERE id = ?`,
        [c.title, c.description, c.category, c.level, c.instructor_name, c.thumbnail_url, c.highlights, c.price, c.currency, c.duration_text, c.sort_order, courseId]
      );
      console.log(`Updated course ${c.slug} (ID: ${courseId})`);
    } else {
      const [res] = await db.query(
        `INSERT INTO courses
         (slug, title, description, category, level, instructor_name,
          thumbnail_url, highlights, price, currency, duration_text, sort_order, is_published, created_at, updated_at)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, NOW(), NOW())`,
        [c.slug, c.title, c.description, c.category, c.level, c.instructor_name, c.thumbnail_url, c.highlights, c.price, c.currency, c.duration_text, c.sort_order]
      );
      courseId = res.insertId;
      console.log(`Inserted new course ${c.slug} (ID: ${courseId})`);
    }

    // 2. Upsert lessons for this course
    for (const l of c.lessons) {
      const [existingLesson] = await db.query(
        'SELECT id FROM course_lessons WHERE course_id = ? AND position = ?',
        [courseId, l.position]
      );
      if (existingLesson && existingLesson.length > 0) {
        await db.query(
          `UPDATE course_lessons
           SET title = ?, description = ?, video_url = ?, pdf_url = ?, duration_minutes = ?, is_preview = ?, updated_at = NOW()
           WHERE id = ?`,
          [l.title, l.description, l.video_url, l.pdf_url, l.duration_minutes, l.is_preview, existingLesson[0].id]
        );
      } else {
        await db.query(
          `INSERT INTO course_lessons
           (course_id, position, title, description, video_url, pdf_url, duration_minutes, is_preview, created_at, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, NOW(), NOW())`,
          [courseId, l.position, l.title, l.description, l.video_url, l.pdf_url, l.duration_minutes, l.is_preview]
        );
      }
    }
  }

  const [totalCourses] = await db.query('SELECT COUNT(*) as count FROM courses WHERE is_published = 1');
  const [totalLessons] = await db.query('SELECT COUNT(*) as count FROM course_lessons');
  console.log(`\nDONE! Total published courses in database: ${totalCourses[0].count}`);
  console.log(`Total course lessons in database: ${totalLessons[0].count}`);
  if (require.main === module) {
    process.exit(0);
  }
}

if (require.main === module) {
  seedAllCourses().catch((err) => {
    console.error('Failed to seed courses:', err);
    process.exit(1);
  });
}

module.exports = seedAllCourses;
